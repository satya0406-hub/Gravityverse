export function getModelConfig(modelId: string): ModelConfig | undefined {
  if (!modelId) return MODEL_REGISTRY['auto'];
  return MODEL_REGISTRY[modelId];
}

export function getAllModels(): ModelConfig[] {
  return Object.values(MODEL_REGISTRY);
}

export function getVisibleModels(): ModelConfig[] {
  return Object.values(MODEL_REGISTRY).filter(m => !m.hidden && !m.deprecated);
}

export function getProvidersForModel(modelId: string): { providerId: string; providerModelId: string; priority: number }[] {
  const model = getModelConfig(modelId);
  if (!model) return [];
  return [...model.providerMappings].sort((a, b) => a.priority - b.priority);
}

