export function filterFallbackEvents(
  events: SrmEvent[],
  filters: {
    timeFilter?: string;
    classification?: string;
    category?: string;
    field?: string;
    campus?: string;
    search?: string;
  }
): SrmEvent[] {
  let list = [...events];

  if (filters.classification && filters.classification !== 'all' && filters.classification !== 'for_you') {
    list = list.filter(e => e.classification === filters.classification);
  }

  if (filters.category && filters.category !== 'All') {
    list = list.filter(e => e.category.toLowerCase().includes(filters.category!.toLowerCase()));
  }

  if (filters.field && filters.field !== 'All') {
    list = list.filter(e => 
      e.eligibleFields.some(f => f.toLowerCase() === filters.field!.toLowerCase() || f.toLowerCase() === 'general')
    );
  }

  if (filters.campus && filters.campus !== 'All') {
    list = list.filter(e => 
      (e.campus && e.campus.toLowerCase().includes(filters.campus!.toLowerCase())) ||
      (e.venue && e.venue.toLowerCase().includes(filters.campus!.toLowerCase()))
    );
  }

  if (filters.search && filters.search.trim()) {
    const q = filters.search.toLowerCase().trim();
    list = list.filter(e =>
      e.title.toLowerCase().includes(q) ||
      e.description.toLowerCase().includes(q) ||
      e.organizer.toLowerCase().includes(q) ||
      e.venue.toLowerCase().includes(q) ||
      e.category.toLowerCase().includes(q)
    );
  }

  return list;
}
